// dillad's command-key timing is the helper's: protocol/vectors/bot.json command_key_timing is the one source both
// check against (Task 21b fix round 2), so the previous-key overlap dillad computes from not_after cannot drift from
// the slack the helper mints with.
func TestCommandKeyTimingMatchesTheVector(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("..", "..", "protocol", "vectors", "bot.json"))
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Timing *struct {
			MaxLifetime      *int64 `json:"max_lifetime_secs"`
			PublicationSlack *int64 `json:"publication_slack_secs"`
		} `json:"command_key_timing"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatal(err)
	}
	if doc.Timing == nil || doc.Timing.MaxLifetime == nil || doc.Timing.PublicationSlack == nil {
		t.Fatal("bot.json carries no command_key_timing")
	}
	if *doc.Timing.MaxLifetime != maxCommandKeyLifetime {
		t.Fatalf("maxCommandKeyLifetime = %d, vector %d", maxCommandKeyLifetime, *doc.Timing.MaxLifetime)
	}
	if *doc.Timing.PublicationSlack != commandKeyPublicationSlack {
		t.Fatalf("commandKeyPublicationSlack = %d, vector %d", commandKeyPublicationSlack, *doc.Timing.PublicationSlack)
	}
}

// The command-key publication of protocol/vectors/bot.json (sealed_command, generated by
// dilla_core::bot::command) decodes and verifies under dillad's Go check, byte for byte: the
// signing message dillad rebuilds is the one the Rust core signed.
func TestCommandKeyPublicationMatchesTheCoreVector(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("..", "..", "protocol", "vectors", "bot.json"))
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		SealedCommand struct {
			Bot struct {
				Device  string `json:"device"`
				DSKSeed string `json:"dsk_seed"`
			} `json:"bot"`
			CommandKey struct {
				PK string `json:"pk"`
			} `json:"command_key"`
			PublicationHex string `json:"publication_hex"`
			Request        struct {
				CommunityID string `json:"community_id"`
			} `json:"request"`
		} `json:"sealed_command"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatal(err)
	}
	v := doc.SealedCommand
	if v.PublicationHex == "" {
		t.Fatal("bot.json carries no sealed_command publication")
	}
	unhex := func(s string) []byte {
		t.Helper()
		b, err := hex.DecodeString(s)
		if err != nil {
			t.Fatal(err)
		}
		return b
	}
	p, err := decodeCommandKeyPublication(unhex(v.PublicationHex))
	if err != nil {
		t.Fatalf("decode: %v", err)
	}
	community, err := id.Parse(v.Request.CommunityID)
	if err != nil {
		t.Fatal(err)
	}
	device, err := id.Parse(v.Bot.Device)
	if err != nil {
		t.Fatal(err)
	}
	if p.CommunityID != community || p.BotDeviceID != device || hex.EncodeToString(p.PublicKey) != v.CommandKey.PK {
		t.Fatalf("decoded %+v, want community %s device %s pk %s", p, community, device, v.CommandKey.PK)
	}
	pub := ed25519.NewKeyFromSeed(unhex(v.Bot.DSKSeed)).Public().(ed25519.PublicKey)
	if !p.verify(pub) {
		t.Fatal("the core's publication does not verify under the Bot's DSK")
	}
	other := ed25519.NewKeyFromSeed(make([]byte, 32)).Public().(ed25519.PublicKey)
	if p.verify(other) {
		t.Fatal("the publication verified under another key")
	}
	tampered := p
	tampered.NotAfter++
	if tampered.verify(pub) {
		t.Fatal("a changed not_after still verified")
	}
}
