func TestInitialPackageBindsAllCopySourcesAndGeneratedUninstaller(t *testing.T) {
	for _, fault := range []string{"valid", "tampered runtime", "missing uninstaller", "source link"} {
		t.Run(fault, func(t *testing.T) {
			cfg, l := initialInstallation(t)
			payload := t.TempDir()
			if err := os.CopyFS(payload, os.DirFS(l.stableRoot)); err != nil {
				t.Fatal(err)
			}
			for name, raw := range map[string][]byte{"Dilla.exe": []byte("packaged native launcher"), "Uninstall " + cfg.ProductName + ".exe": []byte("generated by original NSIS")} {
				if err := os.WriteFile(filepath.Join(payload, name), raw, 0600); err != nil {
					t.Fatal(err)
				}
			}
			seed, err := os.ReadFile(filepath.Join(l.updates, "windows-active-0.json"))
			if err != nil {
				t.Fatal(err)
			}
			if err = os.WriteFile(filepath.Join(payload, "initial-slot.json"), seed, 0600); err != nil {
				t.Fatal(err)
			}
			switch fault {
			case "tampered runtime":
				entries, e := os.ReadDir(filepath.Join(payload, "versions"))
				if e != nil {
					t.Fatal(e)
				}
				if e = os.WriteFile(filepath.Join(payload, "versions", entries[0].Name(), "dilla-desktop.exe"), []byte("unrelated"), 0600); e != nil {
					t.Fatal(e)
				}
			case "missing uninstaller":
				if err = os.Remove(filepath.Join(payload, "Uninstall "+cfg.ProductName+".exe")); err != nil {
					t.Fatal(err)
				}
			case "source link":
				if err = os.Link(filepath.Join(payload, "Dilla.exe"), filepath.Join(payload, "alias.exe")); err != nil {
					t.Fatal(err)
				}
			}
			pkg, err := loadInitialPackage(payload, cfg)
			if (err == nil) != (fault == "valid") {
				if pkg != nil {
					_ = pkg.Close()
				}
				t.Fatalf("unexpected source authorization: %v", err)
			}
			if err != nil {
				return
			}
			defer func() { _ = pkg.Close() }()
			if len(pkg.files) != 4 || string(pkg.seed) != string(seed) {
				t.Fatal("copy authority omitted package entries")
			}
			if _, ok := pkg.files["Uninstall "+cfg.ProductName+".exe"]; !ok {
				t.Fatal("generated fixed uninstaller not staged")
			}
		})
	}
}

func TestCompleteInitialProgramPermitsAuthenticatedEmptyManifestFiles(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "empty.bin")
	if err := os.WriteFile(path, nil, 0600); err != nil {
		t.Fatal(err)
	}
	pkg := &initialPackage{files: map[string]initialCopySource{"empty.bin": {path: path, size: 0, digest: hash(nil)}}}
	if err := verifyCompleteInitialProgram(root, pkg); err != nil {
		t.Fatal(err)
	}
}

func TestInitialPackageRejectsAuthenticatedReleaseSlotAsSeed(t *testing.T) {
	cfg, l := initialInstallation(t)
	_, release := committedUpgrade(t, &cfg, l)
	payload := t.TempDir()
	if err := os.CopyFS(payload, os.DirFS(l.stableRoot)); err != nil {
		t.Fatal(err)
	}
	for name, raw := range map[string][]byte{"Dilla.exe": []byte("same launcher"), initialUninstallerName(cfg): []byte("generated uninstaller"), "initial-slot.json": release} {
		if err := os.WriteFile(filepath.Join(payload, name), raw, 0600); err != nil {
			t.Fatal(err)
		}
	}
	// VerifySlot with an empty provenance root really can authenticate this release
	// relative to the working directory. Initial copy must reject its kind anyway.
	t.Chdir(l.updates)
	slot, err := desktoplaunch.VerifySlot(release, cfg.trust(), "", time.Now())
	if err != nil || slot.Kind != "release" {
		t.Fatalf("authenticated release control: %v", err)
	}
	pkg, err := loadInitialPackage(payload, cfg)
	if err == nil {
		_ = pkg.Close()
		t.Fatal("accepted an authenticated release as generation-zero initial seed")
	}
}
