import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const output = new URL('../internal/desktopauth/browser.js', import.meta.url);
const result = await build({ entryPoints: [new URL('../packages/web/src/desktop-auth-browser.ts', import.meta.url).pathname], bundle: true, platform: 'browser', target: 'es2022', format: 'iife', write: false });
const text = '// Generated by scripts/build-desktop-auth.mjs.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== text) throw new Error('Run node scripts/build-desktop-auth.mjs and commit browser.js');
} else await writeFile(output, text);
