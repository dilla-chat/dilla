#!/usr/bin/env node
/**
 * Generates the GPUI desktop client's design tokens and icons from the web design system, so a token can be traced across both:
 *   packages/design-tokens/src/tokens.ts (theme "signal")  ->  clients/desktop/dilla-desktop-ui/src/tokens.rs
 *   packages/ui/src/Icon/icons.ts                          ->  clients/desktop/dilla-desktop-ui/assets/icons/*.svg
 *                                                              clients/desktop/dilla-desktop-ui/src/icon_names.rs
 * Names mirror packages/design-tokens/src/css.ts: `--fg-2` is `color::FG_2`, `--text-btn` is `text::BTN`, `--r-md` is `radius::MD`.
 * `node scripts/gen-gpui-tokens.mjs` writes; `--check` writes nothing and exits 1 when a generated file is stale
 * (scripts/gen-gpui-tokens.test.mjs runs it, and `npm run ci:local` runs that test).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const UI = join(ROOT, 'clients', 'desktop', 'dilla-desktop-ui');

/** The CSS custom property's name (css.ts): `fgBody` -> `fg-body`, `bg2` -> `bg-2`. */
export function kebab(key) {
  return key.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
}
/** `fgBody` -> `FG_BODY`, `bg2` -> `BG_2`, `poll-voter` -> `POLL_VOTER`. */
const constName = (key) => kebab(key).replace(/-/g, '_').toUpperCase();
const pascal = (name) => name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

/** `#RRGGBB` or `rgba(r,g,b,a)` (alpha may be `.1`) to [r,g,b,a] with r,g,b in 0..255. */
export function parseColor(value) {
  let m = /^#([0-9a-f]{6})$/i.exec(value);
  if (m) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16)).concat(1);
  m = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)$/.exec(value);
  if (m) return [Number(m[1]), Number(m[2]), Number(m[3]), Number(m[4])];
  throw new Error(`unsupported colour ${value}`);
}

/** RGB 0..255 to GPUI's HSL, every component 0..1. */
export function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  let h = 0, s = 0;
  if (d !== 0) {
    s = d / (1 - Math.abs(2 * l - 1));
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h = (((h * 60) + 360) % 360) / 360;
  }
  return [h, s, l];
}
const f = (n) => { const s = Number(n.toFixed(6)).toString(); return s.includes('.') || s.includes('e') ? s : `${s}.0`; };

function px(value) {
  const m = /^([0-9.]+)(px|rem)$/.exec(value);
  if (!m) throw new Error(`expected px or rem, got ${value}`);
  return m[2] === 'rem' ? Number(m[1]) * 16 : Number(m[1]);
}

// The web token -> the Rust constant, for the names the brief fixes; any other layout token keeps its own name.
const LAYOUT = { railW: 'RAIL', slotW: 'SLOT', sidebarW: 'SIDEBAR', membersW: 'MEMBERS', threadW: 'THREAD', barH: 'BAR', panelH: 'USER_PANEL', rowH: 'ROW', topbarH: 'TOPBAR', bottombarH: 'BOTTOMBAR' };

export async function generate() {
  const { themes, structural } = await import(pathToFileURL(join(ROOT, 'packages/design-tokens/src/tokens.ts')).href);
  const { ICONS } = await import(pathToFileURL(join(ROOT, 'packages/ui/src/Icon/icons.ts')).href);
  const signal = themes.signal;
  const files = new Map();

  const out = [];
  out.push('// @generated by scripts/gen-gpui-tokens.mjs from packages/design-tokens/src/tokens.ts (theme "signal"). Do not edit.', '//! The Signal design tokens: colours, type scale, radii, layout.', '', '#![allow(missing_docs)]', '');
  out.push('/// Colours (`--<name>` in packages/design-tokens/dist/tokens.css). Translucent ones keep the web alpha.', 'pub mod color {', '    use gpui::{Hsla, hsla};', '');
  for (const [key, value] of Object.entries(signal)) {
    if (key === 'linkUnderline') continue;
    const rgba = parseColor(String(value));
    const [h, s, l] = toHsl(rgba);
    out.push(`    /// \`--${kebab(key)}\`: ${value}`, `    pub const ${constName(key)}: Hsla = hsla(${f(h)}, ${f(s)}, ${f(l)}, ${f(rgba[3])});`);
  }
  out.push('}', '');
  out.push('/// The type scale in logical pixels (`--text-<name>`; the web scale is rem at a 16px root).', 'pub mod text {', '    use gpui::{Pixels, px};', '');
  for (const [key, value] of Object.entries(structural.text)) out.push(`    /// \`--text-${key}\`: ${value}`, `    pub const ${constName(key)}: Pixels = px(${f(px(value))});`);
  out.push('}', '');
  out.push('/// Corner radii (`--r-<name>`).', 'pub mod radius {', '    use gpui::{Pixels, px};', '');
  for (const [key, value] of Object.entries(structural.radius)) out.push(`    /// \`--r-${key}\`: ${value}`, `    pub const ${constName(key)}: Pixels = px(${f(px(value))});`);
  out.push('}', '');
  out.push('/// Pane widths and bar and row heights (`--rail-w`, `--sidebar-w`, `--bar-h`, `--panel-h`, `--row-h`, ...).', 'pub mod layout {', '    use gpui::{Pixels, px};', '');
  for (const [key, value] of Object.entries(structural.layout)) out.push(`    /// \`--${kebab(key)}\`: ${value}`, `    pub const ${LAYOUT[key] ?? constName(key)}: Pixels = px(${f(px(value))});`);
  out.push('}', '');
  out.push('/// Font families and weights (`--font-mono`, `--font-serif-italic`, `--weight-<name>`).', 'pub mod font {', '    use gpui::FontWeight;', '');
  out.push('    /// The family name the registered JetBrains Mono Variable font answers to.', '    pub const MONO: &str = "JetBrains Mono";');
  out.push('    /// The family name the registered DM Serif Display Italic font answers to.', '    pub const SERIF_ITALIC: &str = "DM Serif Display";');
  for (const [key, value] of Object.entries(structural.weight)) out.push(`    /// \`--weight-${key}\`: ${value}`, `    pub const WEIGHT_${constName(key)}: FontWeight = FontWeight(${f(Number(value))});`);
  out.push('}', '');
  out.push('/// Durations (`--duration-<name>`).', 'pub mod motion {', '    use std::time::Duration;', '');
  for (const [key, value] of Object.entries(structural.motion)) {
    if (key === 'easeOut') continue;
    const m = /^([0-9.]+)(ms|s)$/.exec(value);
    const ms = Math.round(Number(m[1]) * (m[2] === "s" ? 1000 : 1));
    out.push(`    /// \`--duration-${kebab(key)}\`: ${value}`, `    pub const ${constName(key)}: Duration = Duration::from_millis(${ms});`);
  }
  out.push('}', '');
  out.push(
    '#[cfg(test)]', 'mod tests {', '    use super::*;', '    use gpui::{Rgba, rgb};', '',
    '    /// The packages/design-tokens CSS this file mirrors.',
    '    const CSS: &str = include_str!("../../../../packages/design-tokens/dist/tokens.css");', '',
    '    fn assert_rgb(actual: gpui::Hsla, hex: u32) {',
    '        let (got, want): (Rgba, Rgba) = (actual.to_rgb(), rgb(hex));',
    '        for (g, w) in [(got.r, want.r), (got.g, want.g), (got.b, want.b)] {',
    '            assert!((g - w).abs() < 1.0 / 512.0, "{actual:?} is not #{hex:06X}");',
    '        }',
    '        assert!((got.a - 1.0).abs() < f32::EPSILON);',
    '    }', '',
    '    #[test]',
    '    fn matches_css() {',
    '        assert_rgb(color::BG, 0x08_09_0B);',
    '        assert_rgb(color::ACCENT, 0x5A_A8_E6);',
    '        assert_eq!(text::BASE, gpui::px(13.5));',
    '        for decl in ["--bg: #08090B;", "--accent: #5AA8E6;", "--text-base: 0.84375rem;", "--rail-w: 56px;", "--sidebar-w: 244px;"] {',
    '            assert!(CSS.contains(decl), "dist/tokens.css lacks {decl}");',
    '        }',
    '    }', '',
    '    #[test]',
    '    fn layout_matches_the_brief() {',
    '        let px = |p: gpui::Pixels| f32::from(p);',
    '        assert_eq!([layout::RAIL, layout::SIDEBAR, layout::MEMBERS, layout::THREAD, layout::BAR, layout::USER_PANEL, layout::ROW].map(px),',
    '            [56.0, 244.0, 232.0, 340.0, 44.0, 64.0, 28.0]);',
    '    }',
    '}', '');
  files.set(join(UI, 'src', 'tokens.rs'), out.join('\n'));

  const names = Object.keys(ICONS);
  const variants = names.map((n) => [n, pascal(n)]);
  if (new Set(variants.map((v) => v[1])).size !== names.length) throw new Error('two icons share a Rust variant name');
  const icons = ['// @generated by scripts/gen-gpui-tokens.mjs from packages/ui/src/Icon/icons.ts. Do not edit.', '//! One variant per icon of the web design system (Lucide, 24x24, stroke 2, round caps and joins).', '', '#![allow(missing_docs)]', '',
    '/// An icon of the design system. Its SVG is `assets/icons/<name>.svg`.', '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]', 'pub enum IconName {'];
  for (const [, v] of variants) icons.push(`    ${v},`);
  icons.push('}', '', 'impl IconName {', "    /// Every icon, in the web design system's order.", `    pub const ALL: [IconName; ${names.length}] = [`);
  for (const [, v] of variants) icons.push(`        IconName::${v},`);
  icons.push('    ];', '', "    /// The icon's name in the web design system (`data-icon`), such as `volume-2`.", "    pub const fn name(self) -> &'static str {", '        match self {');
  for (const [n, v] of variants) icons.push(`            IconName::${v} => "${n}",`);
  icons.push('        }', '    }', '', '    /// The asset path GPUI loads the SVG from (see `theme::Assets`).', "    pub const fn path(self) -> &'static str {", '        match self {');
  for (const [n, v] of variants) icons.push(`            IconName::${v} => "icons/${n}.svg",`);
  icons.push('        }', '    }', '', '    /// The SVG source, embedded in the binary.', "    pub const fn svg(self) -> &'static [u8] {", '        match self {');
  for (const [n, v] of variants) icons.push(`            IconName::${v} => include_bytes!("../assets/icons/${n}.svg"),`);
  icons.push('        }', '    }', '}', '');
  files.set(join(UI, 'src', 'icon_names.rs'), icons.join('\n'));

  for (const [name, nodes] of Object.entries(ICONS)) {
    const body = nodes.map(([tag, attrs]) => `  <${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('\n');
    files.set(join(UI, 'assets', 'icons', `${name}.svg`),
      `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n${body}\n</svg>\n`);
  }
  return files;
}

/** The stale generated files (changed, missing, or an SVG no icon owns any more). */
export async function stale() {
  const files = await generate();
  const bad = [];
  for (const [path, text] of files) if (!existsSync(path) || readFileSync(path, 'utf8') !== text) bad.push(path);
  const dir = join(UI, 'assets', 'icons');
  if (existsSync(dir)) for (const name of readdirSync(dir)) if (!files.has(join(dir, name))) bad.push(join(dir, name));
  return bad;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const bad = await stale();
    if (bad.length > 0) { console.error(`stale generated files (run node scripts/gen-gpui-tokens.mjs):\n${bad.map((p) => `  ${p}`).join('\n')}`); process.exit(1); }
  } else {
    const files = await generate();
    const dir = join(UI, 'assets', 'icons');
    mkdirSync(dir, { recursive: true });
    for (const name of readdirSync(dir)) if (!files.has(join(dir, name))) rmSync(join(dir, name));
    for (const [path, text] of files) writeFileSync(path, text);
    console.log(`wrote ${files.size} files`);
  }
}
