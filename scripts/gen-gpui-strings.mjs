#!/usr/bin/env node
/**
 * Generates the GPUI desktop client's strings from the web client's, so one key names one copy in both:
 *   packages/web/src/strings/en.ts (and the files it spreads)  ->  clients/desktop/dilla-desktop/src/strings.rs
 * The table is sorted by key and read by binary search (`strings::t`, `strings::tf`).
 * `node scripts/gen-gpui-strings.mjs` writes; `--check` writes nothing and exits 1 when the file is stale
 * (scripts/gen-gpui-strings.test.mjs runs it, and `npm run ci:local` runs that test).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'clients', 'desktop', 'dilla-desktop', 'src', 'strings.rs');

/** A Rust string literal for `s`: only `\`, `"` and control characters are escaped, the rest stays as written. */
export function rustString(s) {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (c < 0x20 || c === 0x7f || c === 0x2028 || c === 0x2029 || c === 0x200b || c === 0xfeff) out += `\\u{${c.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

/** The sorted [key, value] pairs of the web client's `en` table. */
export async function entries() {
  const { en } = await import(pathToFileURL(join(ROOT, 'packages', 'web', 'src', 'strings', 'en.ts')).href);
  // Copy the web keeps outside `en` (the shared unsaved-settings guard, not re-exported by the catalog), under a prefix.
  const { settingsEditing } = await import(pathToFileURL(join(ROOT, 'packages', 'web', 'src', 'strings', 'settingsEditing.ts')).href);
  const extra = Object.fromEntries(Object.entries(settingsEditing).map(([k, v]) => [`settings.editing.${k}`, v]));
  return Object.entries({ ...en, ...extra }).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

export async function generate() {
  const list = await entries();
  const rows = list.map(([k, v]) => `    (${rustString(k)}, ${rustString(v)}),`).join('\n');
  return `// @generated by scripts/gen-gpui-strings.mjs from packages/web/src/strings/*.ts. Do not edit; run the script.
//! The user-visible strings, the same copy as the web client's: \`t("activity.title")\` and
//! \`tf("activity.newCount", &[("n", "3")])\`. Keys are the web's flat dot-separated keys; \`{name}\` is a placeholder.

/// Every string, sorted by key.
#[rustfmt::skip]
pub static STRINGS: [(&str, &str); ${list.length}] = [
${rows}
];

/// The string for \`key\`, or \`None\` when the web client has no such key.
pub fn try_t(key: &str) -> Option<&'static str> {
    STRINGS
        .binary_search_by(|(k, _)| (*k).cmp(key))
        .ok()
        .map(|i| STRINGS[i].1)
}

/// The string for \`key\`. A key the web client does not have is a programming error: debug builds panic, release builds
/// draw the empty string.
pub fn t(key: &str) -> &'static str {
    match try_t(key) {
        Some(s) => s,
        None => {
            debug_assert!(false, "strings: no key {key}");
            ""
        }
    }
}

/// The string for \`key\` with each \`{name}\` replaced by its value in \`vars\`. A placeholder with no variable is a
/// programming error, as in the web's \`t\`: debug builds panic, release builds leave it as written.
pub fn tf(key: &str, vars: &[(&str, &str)]) -> String {
    let src = t(key);
    let mut out = String::with_capacity(src.len() + 8);
    let mut rest = src;
    while let Some(open) = rest.find('{') {
        out.push_str(&rest[..open]);
        let after = &rest[open + 1..];
        match after.find('}') {
            Some(close) => {
                let name = &after[..close];
                match vars.iter().find(|(n, _)| *n == name) {
                    Some((_, v)) => out.push_str(v),
                    None => {
                        debug_assert!(false, "strings: {key} needs {{{name}}}");
                        out.push_str(&rest[open..open + close + 2]);
                    }
                }
                rest = &after[close + 1..];
            }
            None => {
                out.push_str(&rest[open..]);
                rest = "";
            }
        }
    }
    out.push_str(rest);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn t_and_tf_read_the_web_copy() {
        assert_eq!(t("activity.title"), "Activity");
        assert_eq!(tf("activity.newCount", &[("n", "3")]), "3 new");
        assert_eq!(
            tf("activity.where", &[("server", "dilla"), ("channel", "general")]),
            "dilla · #general"
        );
        assert_eq!(try_t("no.such.key"), None);
    }

    #[test]
    fn the_table_is_sorted_and_has_no_empty_value() {
        assert!(STRINGS.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(STRINGS.iter().all(|(_, v)| !v.trim().is_empty()));
    }
}
`;
}

export async function stale() {
  const text = await generate();
  return !existsSync(OUT) || readFileSync(OUT, 'utf8') !== text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (await stale()) { console.error('stale generated file (run node scripts/gen-gpui-strings.mjs):\n  ' + OUT); process.exit(1); }
  } else {
    writeFileSync(OUT, await generate());
    console.log(`wrote ${OUT}`);
  }
}
